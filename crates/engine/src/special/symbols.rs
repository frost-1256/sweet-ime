//! Named Unicode symbols and their Japanese readings.

pub(crate) fn symbol_candidates(reading: &str) -> &'static [&'static str] {
    if reading.chars().any(|c| matches!(c, 'ァ'..='ヶ')) {
        let hiragana: String = reading
            .chars()
            .map(|c| match c {
                'ァ'..='ヶ' => char::from_u32(c as u32 - 0x60).unwrap(),
                _ => c,
            })
            .collect();
        return candidates(&hiragana);
    }
    candidates(reading)
}

